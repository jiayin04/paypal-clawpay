"""Dashboard persistence contracts; no driver dependencies."""

from __future__ import annotations

from contextlib import AbstractAsyncContextManager
from datetime import datetime
from typing import Any, Protocol


class UserScopedReader(Protocol):
    """Reads with the caller's JWT (RLS-enforced). Explicit column lists only."""

    async def list_payment_methods(self) -> list[dict[str, Any]]: ...
    async def list_conversations(self, *, limit: int, before: datetime | None) -> list[dict[str, Any]]: ...
    async def get_conversation(self, conversation_id: str) -> dict[str, Any] | None: ...
    async def conversation_events(self, conversation_id: str, *, limit: int, before: datetime | None) -> list[dict[str, Any]]: ...
    async def a2a_messages(self, order_id: str, *, limit: int, before: datetime | None) -> list[dict[str, Any]]: ...
    async def audit_events(self, *, limit: int, before: datetime | None) -> list[dict[str, Any]]: ...
    async def timeline(self, order_id: str, *, limit: int, before: datetime | None) -> list[dict[str, Any]]: ...


    async def list_orders(self, *, limit: int, before: datetime | None) -> list[dict[str, Any]]: ...

    async def get_order_detail(self, order_id: str) -> dict[str, Any] | None: ...

    async def list_devices(self) -> list[dict[str, Any]]: ...


class UserScopedReaderFactory(Protocol):
    def __call__(self, jwt: str) -> AbstractAsyncContextManager[UserScopedReader]: ...
